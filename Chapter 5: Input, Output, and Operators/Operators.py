a = 10
b = 3

print(a + b)   # 13  → Addition
print(a - b)   # 7   → Subtraction
print(a * b)   # 30  → Multiplication
print(a / b)   # 3.33 → Division (float aata hai)
print(a // b)  # 3   → Floor Division (decimal cut ho jata hai)
print(a % b)   # 1   → Modulus (remainder deta hai)
print(a ** b)  # 1000 → Power (a ki power b)